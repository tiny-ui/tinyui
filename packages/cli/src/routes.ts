// `tinyui routes`: types navigation against the package's own pages (docs/build-chain.md §10).
import { dirname, relative, sep } from "node:path";

/**
 * The declaration that makes `navigation.push` / `replace` know this package's pages: each page name with the props
 * of that page, read off its default export by the type checker rather than parsed here. [out] is where the file
 * will live; the pages are imported relative to it, without extension.
 */
export function routesTypes(pkg: string, pages: Map<string, string>, out: string): string {
    const lines = [...pages].map(([name, file]) => {
        let path = relative(dirname(out), file).split(sep).join("/").replace(/\.tsx?$/, "");
        if (!path.startsWith(".")) path = `./${path}`;
        return `        ${JSON.stringify(name)}: PageProps<typeof import(${JSON.stringify(path)})>;`;
    });
    return [
        "// Generated by `tinyui routes` from the pages directory; do not edit.",
        'import type { PageProps } from "tinyui-native";',
        "",
        'declare module "tinyui-native" {',
        "    interface RoutePackage {",
        `        name: ${JSON.stringify(pkg)};`,
        "    }",
        "    interface Routes {",
        ...lines,
        "    }",
        "}",
        "",
    ].join("\n");
}
